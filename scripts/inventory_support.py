"""Safe parsing, source binding, and recoverable writes for Homebrew inventories."""

from contextlib import contextmanager
from dataclasses import dataclass, field
import fcntl
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tempfile


HEADER = "# Generated by python3 scripts/sync_homebrew.py; move entries between sections to customize groups."
SUMMARY = "# Requested formulae, installed casks, and any desired entries kept from previous syncs."
CUSTOM = "# -- Custom content --"
SECTION = re.compile(r"^# -- (Formulae|Casks): (.+) --$")
ENTRY = re.compile(r"^(tap|brew|cask)\s+([\"'])([A-Za-z0-9+_.@/-]+)\2(.*)$")
STATE = ".sync-state.json"
JOURNAL = ".sync-transaction.json"
STAGING = ".sync-transaction"
FILES = {"Brewfile", "dependencies.txt", STATE}


def split_arguments(value):
    """Split literal Ruby arguments without evaluating user code."""
    pieces, stack = [], []
    start, quote, escaped = 0, None, False
    for index, char in enumerate(value):
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            continue
        if char in "\"'":
            quote = char
        elif char in "[{":
            stack.append(char)
        elif char in "]}":
            if not stack or stack.pop() != {"]": "[", "}": "{"}[char]:
                raise ValueError("unbalanced argument")
        elif char == "#" and not stack:
            pieces.append(value[start:index].strip())
            return [part for part in pieces if part], value[index:]
        elif char == "," and not stack:
            piece = value[start:index].strip()
            if not piece:
                raise ValueError("empty argument")
            pieces.append(piece)
            start = index + 1
    if quote or stack:
        raise ValueError("multiline or unbalanced argument")
    last = value[start:].strip()
    if last:
        pieces.append(last)
    return pieces, ""


def literal(value):
    if re.fullmatch(r"(?:true|false|nil|:[A-Za-z_]\w*|-?\d+(?:\.\d+)?)", value):
        return True
    if re.fullmatch(r'''"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*' ''', value, re.VERBOSE):
        return not (value.startswith('"') and "#{" in value)
    if value.startswith("[") and value.endswith("]"):
        parts, comment = split_arguments(value[1:-1])
        return not comment and all(literal(part) for part in parts)
    if value.startswith("{") and value.endswith("}"):
        parts, comment = split_arguments(value[1:-1])
        return not comment and all(
            (match := re.fullmatch(r"[A-Za-z_]\w*:\s*(.+)", part)) and literal(match[1])
            for part in parts
        )
    return False


@dataclass
class Entry:
    kind: str
    name: str
    line: str
    positional: list = field(default_factory=list)
    options: dict = field(default_factory=dict)
    comment: str = ""


def parse_entry(line):
    match = ENTRY.fullmatch(line)
    if not match:
        raise ValueError("expected a simple tap, brew, or cask entry")
    kind, _, name, suffix = match.groups()
    suffix = suffix.strip()
    if suffix and not suffix.startswith((",", "#")):
        raise ValueError("conditional or executable Ruby expression")
    if suffix.startswith(",") and (not suffix[1:].strip() or suffix[1:].lstrip().startswith("#")):
        raise ValueError("incomplete or multiline argument")
    parts, comment = split_arguments(suffix[1:].strip() if suffix.startswith(",") else suffix)
    entry = Entry(kind, name, line, comment=comment)
    for part in parts:
        option = re.fullmatch(r"([A-Za-z_]\w*):\s*(.+)", part)
        if option:
            key, value = option.groups()
            if key in entry.options or not literal(value):
                raise ValueError("duplicate option or executable Ruby argument")
            entry.options[key] = value
        elif kind == "tap" and not entry.positional and part.startswith(('"', "'")) and literal(part):
            entry.positional.append(part)
        else:
            raise ValueError("unsupported positional argument")
    return entry


@dataclass
class Document:
    taps: dict = field(default_factory=dict)
    groups: dict = field(default_factory=lambda: {"brew": {}, "cask": {}})
    notes: dict = field(default_factory=dict)
    trailing_notes: list = field(default_factory=list)
    custom: str = ""


def read_document(path):
    document = Document()
    if not path.exists():
        return document
    source_text = path.read_text()
    lines = source_text.splitlines()
    families = {match[3].rsplit("/", 1)[-1].split("@", 1)[0]
                for line in lines if (match := ENTRY.fullmatch(line)) and "@" in match[3]}
    current, pending = None, []
    for index, line in enumerate(lines):
        if line == CUSTOM:
            document.custom = "".join(source_text.splitlines(keepends=True)[index:])
            break
        if line in {HEADER, SUMMARY, "# -- Taps --"} or line in {f"## {name}" for name in families}:
            continue
        if match := SECTION.fullmatch(line):
            current = ("brew" if match[1] == "Formulae" else "cask", match[2])
        elif line.lstrip().startswith("#"):
            pending.append(line)
        elif line.strip():
            try:
                entry = parse_entry(line)
            except ValueError as error:
                raise RuntimeError(
                    f"{path}:{index + 1}: {error}. Move custom Ruby or other package types "
                    f"after '{CUSTOM}'; nothing has been overwritten."
                ) from error
            key = (entry.kind, entry.name)
            if key in document.notes:
                raise RuntimeError(f"{path}:{index + 1}: duplicate {entry.kind} entry: {entry.name}")
            document.notes[key] = pending
            pending = []
            if entry.kind == "tap":
                document.taps[entry.name] = line
            else:
                group = current[1] if current and current[0] == entry.kind else "New installs"
                document.groups[entry.kind][entry.name] = (group, line)
    document.trailing_notes = pending
    return document


def merge_entry(previous, current, last_generated=None):
    """Refresh generated options; keep options edited or supplied by the user."""
    if previous is None:
        return current
    old, new = parse_entry(previous), parse_entry(current)
    prior = parse_entry(last_generated) if last_generated else None
    positional = new.positional
    if old.positional and (prior is None or old.positional != prior.positional):
        positional = old.positional
    elif prior and prior.positional and not old.positional:
        positional = []
    options = dict(new.options)
    for key, value in old.options.items():
        if prior is None or value != prior.options.get(key):
            options[key] = value
    if prior:
        for key in prior.options.keys() - old.options.keys():
            options.pop(key, None)
    if positional == old.positional and options == old.options:
        return previous
    suffix = positional + [f"{key}: {value}" for key, value in options.items()]
    return (f'{old.kind} "{old.name}"' + (", " + ", ".join(suffix) if suffix else "")
            + (" " + old.comment if old.comment else ""))


def machine_identity():
    if platform.system() == "Linux":
        for path in (Path("/etc/machine-id"), Path("/var/lib/dbus/machine-id")):
            if path.is_file() and (identifier := path.read_text().strip()):
                return identifier
    elif platform.system() == "Darwin":
        result = subprocess.run(["ioreg", "-rd1", "-c", "IOPlatformExpertDevice"],
                                text=True, capture_output=True, check=True)
        if match := re.search(r'"IOPlatformUUID"\s*=\s*"([^"]+)"', result.stdout):
            return match[1]
    raise RuntimeError("Cannot identify this machine reliably; no inventory was written.")


def source_identity(prefix):
    return {"machine": hashlib.sha256(machine_identity().encode()).hexdigest(),
            "prefix": str(Path(prefix).resolve()), "architecture": platform.machine()}


def read_state(directory):
    path = directory / STATE
    if not path.exists():
        return None
    try:
        state = json.loads(path.read_text())
        if (state.get("schema") != 1 or not isinstance(state.get("source"), dict)
                or not isinstance(state.get("settings"), dict)):
            raise ValueError("unsupported or invalid state schema")
        if "deduplicate_casks" in state and not isinstance(state["deduplicate_casks"], bool):
            raise ValueError("invalid cask deduplication policy")
        for key in ("machine", "prefix", "architecture"):
            if not isinstance(state["source"].get(key), str) or not state["source"][key]:
                raise ValueError("missing source identity")
        for key, value in state["settings"].items():
            entry = parse_entry(value)
            if key != f"{entry.kind}:{entry.name}":
                raise ValueError("invalid saved entry")
        return state
    except (ValueError, AttributeError, TypeError) as error:
        raise RuntimeError(f"Cannot read {path}: {error}") from error


def validate_source(directory, state, source, adopt=False):
    if adopt:
        return
    if state is None:
        if (directory / "Brewfile").exists():
            raise RuntimeError(f"{directory} has an unbound inventory. Use --adopt once to bind it "
                               "to this machine/install, or --profile NAME for a separate inventory.")
    elif state["source"] != source:
        raise RuntimeError(f"{directory} belongs to a different machine or Homebrew installation. "
                           "Use --profile NAME for a separate inventory, or --adopt to rebind it.")


def fsync_directory(directory):
    descriptor = os.open(directory, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def atomic_write(path, data):
    """Durably replace a complete file, preserving existing permissions."""
    descriptor, temporary = tempfile.mkstemp(prefix=".sync-write-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            os.fchmod(handle.fileno(), path.stat().st_mode & 0o777 if path.exists() else 0o644)
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
        fsync_directory(path.parent)
    finally:
        Path(temporary).unlink(missing_ok=True)


def recover_transaction(directory):
    journal = directory / JOURNAL
    staging = directory / STAGING
    if not journal.exists():
        # Before the journal is committed, no inventory file has been changed.
        if staging.exists():
            shutil.rmtree(staging)
        return False
    try:
        transaction = json.loads(journal.read_text())
        if (transaction["phase"] not in {"commit", "rollback"}
                or not transaction["files"] or not set(transaction["files"]) <= FILES
                or set(transaction["files"]) != set(transaction["existed"])):
            raise ValueError("invalid transaction manifest")
        direction = "new" if transaction["phase"] == "commit" else "old"
        # Validate every staged file before touching any destination.
        data = {}
        for name in transaction["files"]:
            if direction == "new" or transaction["existed"][name]:
                data[name] = (staging / direction / name).read_bytes()
                digest = hashlib.sha256(data[name]).hexdigest()
                if digest != transaction["hashes"][direction][name]:
                    raise ValueError(f"damaged staged file: {name}")
        for name in transaction["files"]:
            destination = directory / name
            if name in data:
                atomic_write(destination, data[name])
            else:
                destination.unlink(missing_ok=True)
        fsync_directory(directory)
        journal.unlink()
        fsync_directory(directory)
        shutil.rmtree(staging)
        return True
    except (ValueError, KeyError, TypeError) as error:
        raise RuntimeError(f"Cannot recover {journal}: {error}; staged files have been retained.") from error


def commit_files(directory, content):
    """Commit a file set with rollback on errors and roll-forward after a crash."""
    staging = directory / STAGING
    journal = directory / JOURNAL
    if journal.exists() or staging.exists():
        raise RuntimeError("Recover the pending inventory transaction before writing.")
    transaction = {"phase": "commit", "files": [], "existed": {}, "hashes": {"old": {}, "new": {}}}
    try:
        (staging / "new").mkdir(parents=True)
        (staging / "old").mkdir()
        for path, text in content.items():
            if path.parent != directory or path.name not in FILES:
                raise ValueError(f"Invalid inventory destination: {path}")
            name = path.name
            transaction["files"].append(name)
            transaction["existed"][name] = path.exists()
            for direction, data in (("new", text.encode()), ("old", path.read_bytes() if path.exists() else None)):
                if data is not None:
                    atomic_write(staging / direction / name, data)
                    transaction["hashes"][direction][name] = hashlib.sha256(data).hexdigest()
        fsync_directory(staging)
        atomic_write(journal, (json.dumps(transaction) + "\n").encode())
        recover_transaction(directory)
    except (OSError, KeyboardInterrupt):
        if journal.exists():
            transaction["phase"] = "rollback"
            atomic_write(journal, (json.dumps(transaction) + "\n").encode())
            recover_transaction(directory)
        elif staging.exists():
            shutil.rmtree(staging)
        raise


@contextmanager
def inventory_lock(directory, check=False):
    if check:
        lock = directory / ".sync.lock"
        if not lock.exists():
            if (directory / JOURNAL).exists():
                raise RuntimeError("An interrupted sync needs recovery; rerun without --check.")
            yield
            return
        handle = lock.open("rb")
    else:
        directory.mkdir(parents=True, exist_ok=True)
        handle = (directory / ".sync.lock").open("a+b")
    with handle:
        fcntl.flock(handle, fcntl.LOCK_SH if check else fcntl.LOCK_EX)
        try:
            if check and (directory / JOURNAL).exists():
                raise RuntimeError("An interrupted sync needs recovery; rerun without --check.")
            if not check and recover_transaction(directory):
                print("Recovered interrupted inventory sync.")
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)
